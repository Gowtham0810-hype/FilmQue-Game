/**
 * generate-barcode-manifest.cjs
 * 
 * Build-time script that:
 * 1. Reads all movie IDs from movies.ts
 * 2. For each movie, copies its barcode PNG from public/barcodes/<id>.png
 *    to public/barcodes/<sha256hash>.png  (the hash file is what gets served)
 * 3. Writes public/barcode-manifest.json
 * 4. Writes src/shared/barcodeManifest.ts (for zero-fs typed bundling in server & client)
 * 5. Copies to dist/client/barcodes if dist exists
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT_DIR = path.join(__dirname, '..');
const BARCODES_DIR = path.join(ROOT_DIR, 'public', 'barcodes');
const MANIFEST_JSON_PATH = path.join(ROOT_DIR, 'public', 'barcode-manifest.json');
const MANIFEST_TS_PATH = path.join(ROOT_DIR, 'src', 'shared', 'barcodeManifest.ts');
const MOVIES_TS = path.join(ROOT_DIR, 'src', 'client', 'data', 'movies.ts');
const DIST_BARCODES_DIR = path.join(ROOT_DIR, 'dist', 'client', 'barcodes');

// Extract movie IDs from movies.ts using regex on "id": "..."
const tsContent = fs.readFileSync(MOVIES_TS, 'utf8');
const idRegex = /"id":\s*"([^"]+)"/g;
const movieIds = [];
let match;
while ((match = idRegex.exec(tsContent)) !== null) {
  movieIds.push(match[1]);
}

console.log(`Found ${movieIds.length} movie IDs in movies.ts`);

const manifest = {};
let copied = 0;
let missing = 0;

for (const id of movieIds) {
  const srcFile = path.join(BARCODES_DIR, `${id}.png`);
  if (!fs.existsSync(srcFile)) {
    console.warn(`  MISSING barcode: ${id}.png`);
    missing++;
    continue;
  }

  const fileBuffer = fs.readFileSync(srcFile);
  const hash = crypto.createHash('sha256').update(fileBuffer).digest('hex').slice(0, 16);
  const destFile = path.join(BARCODES_DIR, `${hash}.png`);

  if (!fs.existsSync(destFile)) {
    fs.copyFileSync(srcFile, destFile);
    copied++;
  }

  if (fs.existsSync(DIST_BARCODES_DIR)) {
    const distDest = path.join(DIST_BARCODES_DIR, `${hash}.png`);
    if (!fs.existsSync(distDest)) {
      fs.copyFileSync(srcFile, distDest);
    }
  }

  manifest[id] = hash;
}

// 1. Write JSON manifest
fs.writeFileSync(MANIFEST_JSON_PATH, JSON.stringify(manifest, null, 2));

// 2. Write TypeScript manifest (compiled into server & client directly, no runtime fs lookup needed)
const tsModuleContent = `// Auto-generated by generate-barcode-manifest.cjs - DO NOT EDIT DIRECTLY
export const BARCODE_MANIFEST: Record<string, string> = ${JSON.stringify(manifest, null, 2)};
`;
fs.writeFileSync(MANIFEST_TS_PATH, tsModuleContent);

console.log(`Manifest written to ${MANIFEST_JSON_PATH} and ${MANIFEST_TS_PATH}`);
console.log(`Total valid entries: ${Object.keys(manifest).length}, Copied: ${copied}, Missing: ${missing}`);
